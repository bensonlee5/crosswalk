import assert from 'node:assert/strict';
import {actionSound,clockSound} from '../lib/action-sounds.ts';
const p={id:'p',place:'WORK',hours:6,job:0,legacy:0};
assert.equal(actionSound('move','work',p,p),'work');
assert.equal(actionSound('move','study',p,p),'learn');
assert.equal(actionSound('move','friends',p,p),'social');
assert.equal(actionSound('move','rest',p,p),'rest');
assert.equal(actionSound('move','maker_hobby',p,p),'craft');
assert.equal(actionSound('move','move',p,p),'buy');
assert.equal(actionSound('move','visit',p,{...p,place:'THE PARK'}),'travel');
assert.equal(actionSound('move','visit',p,p),null);
assert.equal(actionSound('poll',undefined,p,p),null);
assert.equal(actionSound('move','apply',p,{...p,job:1}),'success');
assert.equal(actionSound('move','end',p,p),'endWeek');
assert.equal(actionSound('move','end',p,p,true),'finish');
assert.equal(clockSound(p,{...p,hours:1}),'tick');
assert.equal(clockSound(p,{...p,hours:0}),'timeUp');
assert.equal(clockSound(p,{...p,hours:6}),null);
assert.equal(clockSound(p,{...p,id:'other',hours:0}),null);
console.log('PASS: action-specific confirmed-result sounds; no poll/no-op sounds; clock alerts only on spent time');
